// The frame-cache budget is process-wide.  Restore it so a test that
// shrinks the budget cannot change the behaviour of later test cases.
class ScopedFrameCacheBudget {
public:
    explicit ScopedFrameCacheBudget(std::size_t bytes)
        : saved_(VideoDecoder::frame_cache_budget()) {
        VideoDecoder::set_frame_cache_budget(bytes);
    }
    ~ScopedFrameCacheBudget() {
        VideoDecoder::set_frame_cache_budget(saved_);
    }
    ScopedFrameCacheBudget(const ScopedFrameCacheBudget&) = delete;
    ScopedFrameCacheBudget& operator=(const ScopedFrameCacheBudget&) = delete;

private:
    std::size_t saved_;
};

bool same_pixels(const cv::Mat& a, const cv::Mat& b) {
    if (a.size() != b.size() || a.type() != b.type()) return false;
    return std::memcmp(a.data, b.data,
                       static_cast<std::size_t>(a.total() * a.elemSize())) == 0;
}

std::vector<std::uint8_t> first_plane_bytes(const AVFrame* f) {
    std::vector<std::uint8_t> out;
    if (!f || !f->data[0] || f->linesize[0] <= 0 || f->height <= 0) return out;
    const auto count = static_cast<std::size_t>(f->linesize[0]) * f->height;
    out.assign(f->data[0], f->data[0] + count);
    return out;
}

